create table if not exists public.participants (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) >= 2),
  usn text not null unique,
  email text not null unique,
  phone text not null unique,
  registration_code text not null unique check (registration_code ~ '^[A-Z0-9]{6}$'),
  qr_data jsonb not null,
  registered_at timestamptz not null default now(),
  attendance_status boolean not null default false,
  checked_in_at timestamptz,
  checked_in_by text,
  scan_device text
);

create table if not exists public.attendance_logs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  registration_code text,
  participant_name text,
  scan_result text not null check (scan_result in ('Success', 'Duplicate Scan', 'Invalid QR')),
  scanner_device text
);

alter table public.participants enable row level security;
alter table public.attendance_logs enable row level security;

drop policy if exists "Participants can register" on public.participants;

