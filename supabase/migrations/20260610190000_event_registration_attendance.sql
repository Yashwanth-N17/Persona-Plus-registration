create or replace function public.register_event_participant(
  participant_name text,
  participant_usn text,
  participant_email text,
  participant_phone text,
  generated_code text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  created_participant participants%rowtype;
  final_participant participants%rowtype;
begin
  insert into participants(name, usn, email, phone, registration_code, qr_data)
  values (
    trim(participant_name),
    upper(trim(participant_usn)),
    lower(trim(participant_email)),
    trim(participant_phone),
    upper(generated_code),
    jsonb_build_object('eventId', 'coffee-alumni-2026', 'participantId', 0, 'code', upper(generated_code))
  )
  returning * into created_participant;

  update participants
  set qr_data = jsonb_build_object(
    'eventId', 'coffee-alumni-2026',
    'participantId', created_participant.id,
    'code', created_participant.registration_code
  )
  where id = created_participant.id
  returning * into final_participant;

  return to_jsonb(final_participant);
end;
$$;

grant execute on function public.register_event_participant(text, text, text, text, text) to anon, authenticated;

create or replace function public.retrieve_participant_by_usn(participant_usn text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  found_participant participants%rowtype;
begin
  select * into found_participant
  from participants
  where usn = upper(trim(participant_usn))
  limit 1;

  if not found then
    return null;
  end if;

  return to_jsonb(found_participant);
end;
$$;

