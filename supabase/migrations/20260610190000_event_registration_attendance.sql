create or replace function public.mark_event_attendance(
  qr_payload_text text,
  volunteer_name text,
  scanner_device_name text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  payload jsonb;
  target_event_id text;
  target_participant_id bigint;
  target_code text;
  found_participant participants%rowtype;
  updated_participant participants%rowtype;
begin
  begin
    payload := qr_payload_text::jsonb;
  exception when others then
    insert into attendance_logs(registration_code, participant_name, scan_result, scanner_device)
    values (null, null, 'Invalid QR', scanner_device_name);
    return jsonb_build_object('status', 'invalid', 'message', 'Invalid or Unregistered QR Code');
  end;

  target_event_id := payload->>'eventId';
  target_code := upper(payload->>'code');

  if (payload->>'participantId') !~ '^[0-9]+$' then
    target_participant_id := null;
  else
    target_participant_id := (payload->>'participantId')::bigint;
  end if;

  if target_event_id is distinct from 'coffee-alumni-2026' or target_participant_id is null or target_code is null then
    insert into attendance_logs(registration_code, participant_name, scan_result, scanner_device)
    values (target_code, null, 'Invalid QR', scanner_device_name);
    return jsonb_build_object('status', 'invalid', 'message', 'QR does not belong to this event.');
  end if;

  select * into found_participant
  from participants
  where id = target_participant_id
    and registration_code = target_code
    and qr_data->>'eventId' = 'coffee-alumni-2026'
  limit 1;

  if not found then
    insert into attendance_logs(registration_code, participant_name, scan_result, scanner_device)
    values (target_code, null, 'Invalid QR', scanner_device_name);
    return jsonb_build_object('status', 'invalid', 'message', 'Invalid or Unregistered QR Code');
  end if;

  if found_participant.attendance_status then
    insert into attendance_logs(registration_code, participant_name, scan_result, scanner_device)
    values (found_participant.registration_code, found_participant.name, 'Duplicate Scan', scanner_device_name);
    return jsonb_build_object(
      'status', 'duplicate',
      'message', 'Previous Check-In Time: ' || found_participant.checked_in_at,
      'checked_in_at', found_participant.checked_in_at,
      'participant', to_jsonb(found_participant)
    );
  end if;

  update participants
  set attendance_status = true,
      checked_in_at = now(),
      checked_in_by = volunteer_name,
      scan_device = scanner_device_name
  where id = found_participant.id
    and attendance_status = false
  returning * into updated_participant;

  insert into attendance_logs(registration_code, participant_name, scan_result, scanner_device)
  values (updated_participant.registration_code, updated_participant.name, 'Success', scanner_device_name);

  return jsonb_build_object(
    'status', 'success',
    'message', 'Checked In Successfully',
    'checked_in_at', updated_participant.checked_in_at,
    'participant', to_jsonb(updated_participant)
  );
end;
$$;

grant execute on function public.mark_event_attendance(text, text, text) to authenticated;

